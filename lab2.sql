-- Лабораторная работа № 2 «Создание запросов».
-- Вариант 30. Таблицы: depots и trams (схема лабораторной № 1, вариант 30).
-- Запросы 1-2 и 7 выполняются по исходным таблицам.
-- Запросы 3-6 работают с отдельной результирующей таблицей и не меняют trams/depots.

-- 1. Все трамваи, которые не проходили капитальный ремонт последние 10 лет.
-- NULL означает, что капитального ремонта никогда не было.
SELECT *
FROM trams
WHERE overhaul_date IS NULL
   OR overhaul_date < (CURRENT_DATE - INTERVAL '10 years')::date
ORDER BY tram_id;

-- 2. Названия и адреса депо, в которых есть трамваи длиннее 27,5 м.
SELECT DISTINCT d.depot_name, d.address
FROM depots AS d
JOIN trams AS t ON t.depot_id = d.depot_id
WHERE t.length_m > 27.5
ORDER BY d.depot_name;

-- 3. Создание таблицы по первому запросу с адресами депо.
-- Перезапуск меняет только созданную для ЛР2 результирующую таблицу.
DROP TABLE IF EXISTS lab2_v30_selected_trams;
CREATE TABLE lab2_v30_selected_trams AS
SELECT t.*, d.depot_name, d.address AS depot_address
FROM trams AS t
JOIN depots AS d ON d.depot_id = t.depot_id
WHERE t.overhaul_date IS NULL
   OR t.overhaul_date < (CURRENT_DATE - INTERVAL '10 years')::date;

-- 4. Добавить в созданную таблицу трамваи из Октябрьского депо,
-- в названиях моделей которых встречаются цифры; исключить дубликаты.
INSERT INTO lab2_v30_selected_trams
    (tram_id, depot_id, model, production_year, overhaul_date,
     total_capacity, seat_count, length_m, bogie_count, section_count,
     depot_name, depot_address)
SELECT t.tram_id, t.depot_id, t.model, t.production_year, t.overhaul_date,
       t.total_capacity, t.seat_count, t.length_m, t.bogie_count, t.section_count,
       d.depot_name, d.address
FROM trams AS t
JOIN depots AS d ON d.depot_id = t.depot_id
WHERE d.depot_name ILIKE '%Октябрьск%'
  AND t.model ~ '[0-9]'
  AND NOT EXISTS (
      SELECT 1 FROM lab2_v30_selected_trams AS r
      WHERE r.tram_id = t.tram_id
  );

-- 5. К модели трамваев после капитального ремонта дописать «М».
-- Меняем только созданную таблицу (не исходную таблицу trams).
UPDATE lab2_v30_selected_trams
SET model = model || 'М'
WHERE overhaul_date IS NOT NULL;

-- 6. Удалить из созданной таблицы трамваи депо с неполным адресом.
-- Полный адрес здесь: город, улица/другая часть адреса, номер дома.
DELETE FROM lab2_v30_selected_trams
WHERE depot_address IS NULL
   OR BTRIM(split_part(depot_address, ',', 1)) = ''
   OR split_part(depot_address, ',', 2) !~ '[^[:space:][:digit:]]'
   OR depot_address !~ '[[:digit:]][[:space:]]*$';

-- 7. Среднее число сидячих мест по каждому году выпуска (все исходные трамваи).
SELECT production_year,
       COUNT(*) AS tram_count,
       ROUND(AVG(seat_count), 2) AS average_seats
FROM trams
GROUP BY production_year
ORDER BY production_year;

