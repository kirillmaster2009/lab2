-- Структура из лабораторной № 1.
CREATE TABLE depots (
    depot_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    depot_name VARCHAR(120) NOT NULL,
    parking_spaces INTEGER NOT NULL CHECK (parking_spaces >= 0),
    repair_spaces INTEGER NOT NULL CHECK (repair_spaces >= 0),
    address TEXT NOT NULL,
    contact_phone VARCHAR(30) NOT NULL
);

CREATE TABLE trams (
    tram_id INTEGER PRIMARY KEY,
    depot_id INTEGER NOT NULL REFERENCES depots(depot_id)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    model VARCHAR(100) NOT NULL,
    production_year INTEGER NOT NULL CHECK (production_year BETWEEN 1900 AND 2100),
    overhaul_date DATE,
    total_capacity INTEGER NOT NULL CHECK (total_capacity > 0),
    seat_count INTEGER NOT NULL CHECK (seat_count >= 0 AND seat_count <= total_capacity),
    length_m NUMERIC(6, 2) NOT NULL CHECK (length_m > 0),
    bogie_count INTEGER NOT NULL CHECK (bogie_count > 0),
    section_count INTEGER NOT NULL CHECK (section_count > 0),
    CONSTRAINT chk_overhaul_after_production CHECK
        (overhaul_date IS NULL OR EXTRACT(YEAR FROM overhaul_date) >= production_year)
);

